import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const variant = process.env.ANDROID_BUILD_TYPE || 'debug';
if (!['debug', 'release'].includes(variant)) throw new Error('Variante Android inválida.');
const sdk = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || (process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk'));
if (!sdk) throw new Error('Android SDK não encontrado para validar a assinatura.');
const jar = path.join(sdk, 'build-tools', '36.0.0', 'lib', 'apksigner.jar');
if (!existsSync(jar)) throw new Error('Instale Android Build Tools 36.0.0.');
const java = process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, 'bin', process.platform === 'win32' ? 'java.exe' : 'java') : 'java';
const apk = path.join(root, 'android/app/build/outputs/apk', variant, `app-${variant}.apk`);
const result = spawnSync(java, ['-jar', jar, 'verify', '--print-certs', apk], { encoding: 'utf8', windowsHide: true });
if (result.error || result.status !== 0) throw new Error('A assinatura do APK não é válida.');
const fingerprint = result.stdout.match(/Signer #1 certificate SHA-256 digest:\s*([a-f\d]+)/i)?.[1]?.toLowerCase();
const expected = (process.env.ANDROID_CERT_SHA256 || '03065720a0d0e03e7fbd20d150f84cf96eff466f75f1a7198244673fde036465').replace(/:/g, '').toLowerCase();
if (!/^[a-f\d]{64}$/.test(expected) || fingerprint !== expected) throw new Error('A chave do APK difere da chave já distribuída. Confira o keystore e ANDROID_CERT_SHA256.');
console.log('APK assinado e compatível com o certificado Android configurado.');
